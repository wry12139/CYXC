# 出口违规词表:只拦"真正的荐股 / 虚假收益承诺"用语。
# 注意:这是交互式概念科普的出口过滤,答案里出现"买入/卖出/对冲/预测"等
# 中性概念动作词是正常的(解释"量化对冲"必然说买入卖出;免责声明"不能预测涨跌"含"预测"),
# 故这些词不入表,避免误杀正当科普。荐股意图由入口 _INTENT + system prompt 双重防住。
# (与 pipeline/ai_rewrite.py 的 BANNED 用途不同——那是新闻改写过滤,此处是概念问答,故有意分开)
BANNED = [
    # 虚假承诺 / 收益保证
    "必涨", "必跌", "稳赚", "包赚", "稳赢", "一定会涨", "一定会跌", "保本高息",
    # 个股炒作标签
    "牛股", "黑马", "潜力股", "金股", "翻倍",
    # 直接荐股 / 内幕
    "荐股", "推荐股票", "目标价", "内幕", "重点关注个股",
    # 明确买卖唆使(短语,非概念词)
    "买它", "值得买入", "梭哈", "上车",
]

SAFE_FALLBACK = "我只能帮你理解概念,不能给出具体买卖或涨跌建议哦~"

# 入口意图词:提问里出现这些即拒答(用户想要买卖/荐股决策)
_INTENT = ["该不该买", "能买吗", "可以买", "值得买", "买不买", "推荐", "买哪",
           "该买", "该卖", "能涨", "会涨", "会跌", "涨到", "跌到", "目标价"]

def has_banned(text):
    return [w for w in BANNED if w in text]

def input_blocked(question):
    return any(w in question for w in _INTENT)
